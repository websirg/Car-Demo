function getVehicleById(id) {
  return VEHICLES_DATA.find(v => v.id === id) || null;
}

function getFeaturedVehicles(limit = 6) {
  return VEHICLES_DATA.filter(v => v.badge.includes("2026") || v.badgeType === "featured" || v.badgeType === "popular").slice(0, limit);
}

function getVehiclesByType(type) {
  return VEHICLES_DATA.filter(v => v.type === type);
}

function getVehiclesByCondition(condition) {
  return VEHICLES_DATA.filter(v => v.condition === condition);
}

function getVehiclesByFuel(fuel) {
  return VEHICLES_DATA.filter(v => v.fuel.toLowerCase() === fuel.toLowerCase());
}

